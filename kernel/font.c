int font_string_width(const char *str) {
    if (!str) return 0;
    int max_w = 0;
    int cur_w = 0;
    while (*str) {
        if (*str == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else {
            cur_w += 8;
        }
        str++;
    }
    if (cur_w > max_w) max_w = cur_w;
    return max_w;
}

int font_string_width_scaled(const char *str, int scale) {
    if (scale <= 0) scale = 1;
    return font_string_width(str) * scale;
}

void font_draw_char(int x, int y, char c, color_t fg, color_t bg) {
    unsigned char uc = (unsigned char)c;
    if (uc < 32 || uc > 126) {
        uc = '?';
    }

    int idx = uc - 32;
    for (int r = 0; r < 16; r++) {
        uint8_t bits = font_data[idx][r];
        for (int b = 0; b < 8; b++) {
            if (bits & (0x80 >> b)) {
                fb_putpixel(x + b, y + r, fg);
            } else if (COLOR_A(bg) > 0) {
                fb_putpixel(x + b, y + r, bg);
            }
        }
    }
}

void font_draw_string(int x, int y, const char *str, color_t fg, color_t bg) {
    if (!str) return;
    int cur_x = x;
    int cur_y = y;

    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 16;
        } else if (*str == '\t') {
            cur_x += 8 * 4;
        } else {
            font_draw_char(cur_x, cur_y, *str, fg, bg);
            cur_x += 8;
        }
        str++;
    }
}

void font_draw_string_scaled(int x, int y, const char *str, color_t fg, color_t bg, int scale) {
    if (!str) return;
    if (scale <= 1) {
        font_draw_string(x, y, str, fg, bg);
        return;
    }

    int cur_x = x;
    int cur_y = y;

    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 16 * scale;
        } else if (*str == '\t') {
            cur_x += 8 * 4 * scale;
        } else {
            unsigned char uc = (unsigned char)*str;
            if (uc < 32 || uc > 126) {
                uc = '?';
            }
            int idx = uc - 32;

            for (int r = 0; r < 16; r++) {
                uint8_t bits = font_data[idx][r];
                for (int b = 0; b < 8; b++) {
                    if (bits & (0x80 >> b)) {
                        gfx_fill_rect(cur_x + b * scale, cur_y + r * scale, scale, scale, fg);
                    } else if (COLOR_A(bg) > 0) {
                        gfx_fill_rect(cur_x + b * scale, cur_y + r * scale, scale, scale, bg);
                    }
                }
            }
            cur_x += 8 * scale;
        }
        str++;
    }
}

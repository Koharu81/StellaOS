#define LANGUAGE_COUNT ((int)(sizeof(g_languages) / sizeof(g_languages[0])))

static int g_current_lang = 0; /* Default to English (index 0) */

void i18n_init(void) {
    g_current_lang = 0; /* Start with English */
}

void i18n_set_language(const char *code) {
    if (!code) return;
    for (int i = 0; i < LANGUAGE_COUNT; i++) {
        if (strcmp(g_languages[i].code, code) == 0) {
            g_current_lang = i;
            return;
        }
    }
}

const char *i18n_get(string_id_t id) {
    if (id < 0 || id >= STR_COUNT) {
        return "";
    }
    const char *str = g_languages[g_current_lang].strings[id];
    if (str && str[0] != '\0') {
        return str;
    }
    /* Fallback to English */
    return g_languages[0].strings[id];
}

const char *i18n_get_lang_name(void) {
    return g_languages[g_current_lang].name;
}

const char *i18n_get_lang_code(void) {
    return g_languages[g_current_lang].code;
}

int i18n_get_language_count(void) {
    return LANGUAGE_COUNT;
}

const language_t *i18n_get_language(int index) {
    if (index < 0 || index >= LANGUAGE_COUNT) {
        return NULL;
    }
    return &g_languages[index];
}
